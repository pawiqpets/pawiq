"""Build theme/assets/pawiq-learn.css from assets/learn/learn.css.

Every rule is scoped under .plx so it cannot leak into the Shopify theme's header, footer or other
sections. Site header/footer and @font-face rules are dropped (the theme has its own). Media queries
are kept in their original order so they still override the base rules.
Usage: python3 _learn/shopify/make_css.py
"""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))
css = open(os.path.join(HERE, "..", "..", "assets", "learn", "learn.css"), encoding="utf-8").read()
DROP = (".site-head", ".logo", ".head-link", ".site-foot")

def scope(sel):
    out = []
    for s in sel.split(","):
        s = s.strip()
        if s == "body":
            out.append(".plx")
        elif s == "main.wrap.wide h1":
            out.append(".plx .wrap.wide h1")
        else:
            out.append(".plx " + s)
    return ",".join(out)

def rules(block):
    res = []
    for m in re.finditer(r"([^{}]+)\{([^{}]*)\}", block):
        sel, body = m.group(1).strip(), m.group(2)
        if sel.startswith((":root", "@font-face", "*", "html", "img")) or sel in ("body",) and False:
            continue
        if sel == "body":
            continue
        if any(sel.startswith(d) for d in DROP):
            continue
        res.append(scope(sel) + "{" + body + "}")
    return res

out = []
root = re.search(r":root\{([^}]*)\}", css).group(1)
body = re.search(r"(?m)^body\{([^}]*)\}", css).group(1)
out.append(".plx{%s;%s;padding-bottom:24px}" % (root, body))
out.append(".plx *{box-sizing:border-box}.plx img{max-width:100%}")
pos = 0
for mq in re.finditer(r"(@media[^{]+)\{((?:[^{}]*\{[^{}]*\})*)\s*\}", css):
    out += rules(css[pos:mq.start()])
    inner = []
    for m in re.finditer(r"([^{}]+)\{([^{}]*)\}", mq.group(2)):
        sel, b = m.group(1).strip(), m.group(2)
        if any(sel.startswith(d) for d in DROP):
            continue
        inner.append((".plx" if sel == "body" else scope(sel)) + "{" + b + "}")
    out.append(mq.group(1) + "{" + "".join(inner) + "}")
    pos = mq.end()
out += rules(css[pos:])
path = os.path.join(HERE, "theme", "assets", "pawiq-learn.css")
open(path, "w", encoding="utf-8").write("/* pawIQ Learn: scoped port of assets/learn/learn.css. Generated by _learn/shopify/make_css.py; do not edit by hand. */\n" + "\n".join(out) + "\n")
print("wrote", path, len(out), "rules")
